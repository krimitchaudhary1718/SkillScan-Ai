/**
 * InterviewSession Model
 * ======================
 * Represents a single AI mock-interview session.
 *
 * Flow:
 *  1. User picks a role, category, and difficulty.
 *  2. AI generates a `questions` array.
 *  3. User submits answers one-by-one; each is evaluated and appended.
 *  4. When all questions are answered the session moves to 'completed'
 *     and an `overallScore` + `feedback` are computed.
 */

import mongoose from 'mongoose';

// -------------------------------------------------------------------
// Sub-schemas (embedded documents)
// -------------------------------------------------------------------

/** A single interview question generated by AI */
const QuestionSchema = new mongoose.Schema(
  {
    question: {
      type: String,
      required: true,
    },
    difficulty: {
      type: String,
      enum: ['easy', 'medium', 'hard'],
      default: 'medium',
    },
    topic: {
      type: String,
      default: 'General',
    },
  },
  { _id: false } // No need for individual _id on sub-docs
);

/** A user's answer + AI evaluation for one question */
const AnswerSchema = new mongoose.Schema(
  {
    questionIndex: {
      type: Number,
      required: true,
      min: 0,
    },
    answer: {
      type: String,
      required: true,
    },
    evaluation: {
      type: Object, // AI-generated evaluation details
      default: null,
      // Expected shape:
      // {
      //   correctness:  Number (0-100),
      //   completeness: Number (0-100),
      //   clarity:      Number (0-100),
      //   feedback:     String,
      //   keyPoints:    [String],
      //   improvements: [String],
      // }
    },
    score: {
      type: Number,
      min: 0,
      max: 100,
      default: 0,
    },
  },
  { _id: false }
);

// -------------------------------------------------------------------
// Main schema
// -------------------------------------------------------------------

const InterviewSessionSchema = new mongoose.Schema(
  {
    userId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: [true, 'User ID is required'],
      index: true,
    },

    // Target job role — e.g., "Frontend Developer", "Data Scientist"
    role: {
      type: String,
      required: [true, 'Role is required'],
      trim: true,
    },

    // Tech category — e.g., "React", "Node.js", "Python"
    category: {
      type: String,
      trim: true,
      default: 'General',
    },

    difficulty: {
      type: String,
      enum: {
        values: ['easy', 'medium', 'hard'],
        message: '{VALUE} is not a valid difficulty',
      },
      default: 'medium',
    },

    // AI-generated questions for this session
    questions: {
      type: [QuestionSchema],
      default: [],
    },

    // User answers + evaluations
    answers: {
      type: [AnswerSchema],
      default: [],
    },

    // Computed after all answers are submitted
    overallScore: {
      type: Number,
      min: 0,
      max: 100,
      default: null,
    },

    // AI-generated summary feedback for the entire session
    feedback: {
      type: String,
      default: '',
    },

    // Session lifecycle
    status: {
      type: String,
      enum: {
        values: ['in-progress', 'completed'],
        message: '{VALUE} is not a valid status',
      },
      default: 'in-progress',
    },
  },
  {
    timestamps: true,
  }
);

// -------------------------------------------------------------------
// Indexes
// -------------------------------------------------------------------
InterviewSessionSchema.index({ userId: 1, createdAt: -1 });
InterviewSessionSchema.index({ status: 1 });

// -------------------------------------------------------------------
// Export guard
// -------------------------------------------------------------------
const InterviewSession =
  mongoose.models.InterviewSession ||
  mongoose.model('InterviewSession', InterviewSessionSchema);

export default InterviewSession;
